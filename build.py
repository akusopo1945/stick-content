#!/usr/bin/env python3
"""
STICKFORGE build tool — workflow baru (Manual AI Studio):

  1. Lu siapkan audio tiap scene dr aistudio.google.com/generate-speech,
     taruh di --in-dir (default G:/PROJECTAN/stick/gemini_in) dgn nama <audio>.mp3
     (nama audio = field "audio" di script JSON).
  2. Lu tulis/edit src/scripts/<nama>.json (deklaratif: scene + teks + visual).
  3. Jalankan:  python3 build.py --script stickman-story/src/scripts/wapres.json
     -> glue audio + timing -> generate src/scenes/<CompositionId>.tsx -> register Root.
  4. Render lokal:  cd stickman-story && npm run render -- <CompositionId> out/<nama>.mp4

Tool gratis: Remotion + ffmpeg + AI Studio. "Premium" dr sistem + editing.
"""
import os, sys, json, re, subprocess, argparse, tempfile
import imageio_ffmpeg
from mutagen.mp3 import MP3

FF = imageio_ffmpeg.get_ffmpeg_exe()
FPS = 30
BASE = "G:/PROJECTAN/stick/stickman-story"
SCRIPTS_DIR = os.path.join(BASE, "src", "scripts")
AUDIO_OUT = os.path.join(BASE, "public", "audio")
DEFAULT_IN = "G:/PROJECTAN/stick/gemini_in"

def die(msg):
    print("ERROR:", msg); sys.exit(1)

def glue(seg_paths, out_path):
    cmd = [FF, "-y"]
    for p in seg_paths:
        cmd += ["-i", p]
    n = len(seg_paths)
    ins = "".join(f"[{i}:a]" for i in range(n))
    cmd += ["-filter_complex", f"{ins}concat=n={n}:v=0:a=1[out]",
            "-map", "[out]", "-ar", "44100", "-ac", "1", "-c:a", "libmp3lame", "-b:a", "128k", out_path]
    subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

def build(script_path, in_dir):
    with open(script_path, encoding="utf-8") as f:
        script = json.load(f)
    title = script["title"]; cid = script["compositionId"]; fade = int(script.get("fade", 12))
    scenes_in = script["scenes"]
    scenes_out, seg_paths, cum = [], [], 0
    for s in scenes_in:
        src = os.path.join(in_dir, s["audio"])
        if not os.path.exists(src):
            die(f"scene '{s['id']}': file audio '{s['audio']}' tak ada di {in_dir}")
        d = MP3(src).info.length
        caps = s.get("captions", [])
        total_chars = max(1, sum(len(c) for c in caps))
        local, cl = [], 0.0
        for c in caps:
            est = d * (len(c) / total_chars)
            cfrom = round(cl * FPS)
            cto = round((cl + est) * FPS)
            # word-level (karaoke) — proportional by char count
            words = c.split(" ")
            wchars = max(1, sum(len(w) for w in words) + (len(words) - 1))
            acc = 0.0
            wlist = []
            for w in words:
                frac = (len(w) + 1) / wchars
                wfrom = round(cfrom + acc * (cto - cfrom))
                wto = round(cfrom + (acc + frac) * (cto - cfrom))
                wlist.append({"t": w, "from": wfrom, "to": wto})
                acc += frac
            local.append({"from": cfrom, "to": cto, "text": c, "pos": "lower", "words": wlist})
            cl += est
        length = round(d * FPS)                       # no tail; overlap = transisi
        cues = []
        for c in local:
            cues.append({
                "from": min(c["from"] + cum, cum + length - 1),
                "to": min(c["to"] + cum, cum + length - 1),
                "text": c["text"], "pos": "lower",
                "words": [{"t": w["t"], "from": min(w["from"] + cum, cum + length - 1),
                          "to": min(w["to"] + cum, cum + length - 1)} for w in c["words"]],
            })
        out = dict(s); out["from"] = cum; out["len"] = length; out["cues"] = cues
        scenes_out.append(out); seg_paths.append(src); cum += length
    total = cum + fade                              # tail fade di ending

    final = os.path.join(AUDIO_OUT, f"{title}_narration.mp3")
    glue(seg_paths, final)
    print(f"Glued audio -> {final}  ({round(MP3(final).info.length,2)}s, {total}f)")

    built = {"title": title, "compositionId": cid,
             "fade": fade, "total": total, "scenes": scenes_out}
    if script.get("voice"):
        built["voice"] = script["voice"]   # hanya sertakan jika ada (hindari null di TS)
    built_path = re.sub(r"\.json$", ".built.json", script_path)
    json.dump(built, open(built_path, "w", encoding="utf-8"), indent=2, ensure_ascii=False)
    print(f"Wrote timing -> {built_path}")

    gen_wrapper(cid, title, built, engine=script.get("engine", "StoryEngine"))
    patch_root(cid, f"{cid}_FRAMES", f"audio/{title}_narration.mp3")
    print(f"OK. Render: cd {BASE} && npm run render -- {cid} out/{title.lower()}.mp4")

def gen_wrapper(cid, title, built, engine="StoryEngine"):
    frames = built["total"]
    data = json.dumps(built, indent=2, ensure_ascii=False)
    tsx = f"""import React from "react";
import {{{engine}, StoryScript}} from "./{engine}";

// Auto-generated by build.py dari {title}.json — jangan edit manual.
const SCRIPT: StoryScript = {data};

export const {cid}_FRAMES = {frames};
export const {cid}: React.FC<{{narration?: string}}> = ({{narration}}) => {{
  const Engine = {engine};
  return <Engine script={{SCRIPT}} narration={{narration ?? "audio/{title}_narration.mp3"}} />;
}};
"""
    out = os.path.join(BASE, "src", "scenes", f"{cid}.tsx")
    open(out, "w", encoding="utf-8").write(tsx)
    print(f"Generated -> {out}")

def patch_root(cid, frames_name, narration):
    root = os.path.join(BASE, "src", "Root.tsx")
    txt = open(root, encoding="utf-8").read()
    # hapus import + Composition lama utk cid ini (idempoten, MULTILINE)
    txt = re.sub(rf'^\s*import\s+[^;]*?from\s+"./scenes/{re.escape(cid)}";\s*\n', "", txt, flags=re.M)
    txt = re.sub(rf'\s*<Composition\s+id="{cid}".*?/>', "", txt, flags=re.S)
    # import di awal
    imp_line = f'import {{{cid}, {frames_name}}} from "./scenes/{cid}";'
    txt = imp_line + "\n" + txt
    # Composition sebelum penutup fragment </> (indent 2 spasi)
    comp = (f'    <Composition\n'
            f'      id="{cid}"\n'
            f'      component={{{cid}}}\n'
            f'      durationInFrames={{{frames_name}}}\n'
            f'      fps={{FPS}}\n'
            f'      width={{W}}\n'
            f'      height={{H}}\n'
            f'      defaultProps={{{{narration: "{narration}"}}}}\n'
            f'    />')
    txt = re.sub(r'(\n\s*</>)', "\n" + comp + r"\1", txt, count=1)
    open(root, "w", encoding="utf-8").write(txt)
    print(f"Patched -> {root}")

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--script", required=True, help="path ke src/scripts/<nama>.json")
    ap.add_argument("--in-dir", default=DEFAULT_IN, help="folder audio scene (.mp3)")
    args = ap.parse_args()
    build(args.script, args.in_dir)

if __name__ == "__main__":
    main()
